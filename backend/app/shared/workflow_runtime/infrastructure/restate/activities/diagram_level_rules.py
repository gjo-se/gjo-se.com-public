"""Diagram level rules for the deterministic processor.

Pure data registry driving ``_build_diagram_proposals`` — one rule per
diagram level, no behaviour. Each rule declares how flat scanner objects
(``{id, name, type, parent}``) map to diagram proposals:

* singleton rule → exactly one global proposal (L1 system context)
* parent rule → one proposal per distinct ``parent`` among objects whose
  ``type`` is in ``scoped_types`` (optionally restricted to systems)

L1 (system context), L2 (container) and L3 (component) proposals are
generated by the scanner. L3 components are persisted objects with
``parent="backend"`` (own ``nodes/*.yml`` like L1/L2), so a ``component``
parent rule yields the ``backend-components`` diagram. L4 (module) is a
pure projection of ``modules[]`` and stays FE-derived.

The union is discriminated by the ``singleton`` literal field.
"""

from __future__ import annotations

from typing import Literal, TypedDict


class SingletonDiagramLevelRule(TypedDict):
    """Rule producing exactly one global diagram proposal (L1)."""

    diagram_type: str
    singleton: Literal[True]
    key: str
    name: str
    description: str
    scoped_types: set[str]


class ParentDiagramLevelRule(TypedDict):
    """Rule producing one diagram proposal per distinct parent (L2/L3).

    ``key_suffix``/``name_suffix`` are appended to the parent id.
    """

    diagram_type: str
    singleton: Literal[False]
    key_suffix: str
    name_suffix: str
    description: str
    scoped_types: set[str]
    parents_must_be_systems: bool


DiagramLevelRule = SingletonDiagramLevelRule | ParentDiagramLevelRule

