"""Unit tests for the deterministic-processor diagram-proposal construction.

Covers the file-safe key builder, the ``scan_meta`` payload and the proposal
derivation (L1 singleton + L2/L3 parent rules) driven by ``DIAGRAM_LEVEL_RULES``.
No DB, no Restate, no file I/O.
"""

from __future__ import annotations

from datetime import UTC, datetime

import pytest

from app.viscera.activities.deterministic_processor.diagrams import (
    _build_diagram_proposals,
    _diagram_key,
    _diagram_scan_meta,
)

pytestmark = pytest.mark.unit

_NOW = datetime(2026, 1, 1, tzinfo=UTC)


@pytest.fixture(autouse=True)
def _prepare_db() -> None:
    """Skip the suite-wide schema bootstrap (unit test without DB)."""
    return


def test_diagram_key_is_file_safe() -> None:
    """Dots in the parent id become dashes; the level suffix is appended."""
    assert _diagram_key("backend", "containers") == "backend-containers"
    assert _diagram_key("app.shared.llm_gateway", "components") == "app-shared-llm_gateway-components"


def test_diagram_scan_meta_carries_source() -> None:
    """The scan_meta carries the timestamp and diagram source tag."""
    assert _diagram_scan_meta(_NOW) == {
        "last_scan_at": _NOW.isoformat(),
        "sources": {"diagram": "deterministic_processor"},
    }


def test_build_diagram_proposals_derives_singleton_and_parent_rules() -> None:
    """L1 singleton plus L2 container and L3 component proposals per parent."""
    merged_objects = [
        {"id": "backend", "type": "system"},
        {"id": "backend.fastapi", "type": "container", "parent": "backend"},
        {"id": "app.shared.llm_gateway", "type": "component", "parent": "backend"},
    ]

    proposals = _build_diagram_proposals(merged_objects, _NOW)

    by_key = {proposal["key"]: proposal for proposal in proposals}
    assert set(by_key) == {"SystemContext", "backend-containers", "backend-components"}

    singleton = by_key["SystemContext"]
    assert singleton["type"] == "systemContext"
    assert singleton["status"] == "pending"
    assert singleton["nodes"] == {}
    assert singleton["scan_meta"]["sources"]["diagram"] == "deterministic_processor"

    container = by_key["backend-containers"]
    assert container["type"] == "container"
    assert container["parent"] == "backend"
    assert container["description"] == (
        "C4 Level 2: Container diagram for system 'backend' (auto-generated by scanner)"
    )

    component = by_key["backend-components"]
    assert component["type"] == "component"
    assert component["parent"] == "backend"
